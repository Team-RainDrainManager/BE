-- 성장 구간표를 Lv.50 만렙 · 누적 5,978점으로 낮췄다 (기존 203,300점).
-- 기존 입양은 저장된 레벨이 옛 구간표 기준이라, 점수를 새 구간표로 다시 계산해 맞춘다.
--
-- 새 구간표는 Lv.1 = 0점, 다음 레벨까지 필요한 점수가 50에서 시작해 레벨마다 3씩 늘어난다.
-- n = level - 1일 때 필요한 점수 T(n) = 1.5n^2 + 48.5n 이므로
-- n = (sqrt(2352.25 + 6 * score) - 48.5) / 3 이다.
UPDATE "adoption"
SET "level" = LEAST(50, GREATEST(1,
        floor((sqrt(2352.25 + 6 * "score") - 48.5) / 3)::int + 1));
