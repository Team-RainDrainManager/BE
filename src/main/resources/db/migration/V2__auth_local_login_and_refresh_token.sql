-- ───────── 자체 로그인(이메일 + 비밀번호) ─────────
ALTER TABLE "users" ADD COLUMN "password" varchar(255);
ALTER TABLE "users" ALTER COLUMN "provider_id" DROP NOT NULL;

COMMENT ON COLUMN "users"."provider" IS 'KAKAO / LOCAL';
COMMENT ON COLUMN "users"."provider_id" IS '카카오 회원번호 (자체 로그인은 null)';
COMMENT ON COLUMN "users"."password" IS 'BCrypt 해시 (자체 로그인만)';

-- 자체 로그인 이메일 중복 방지 (대소문자 무시, 카카오 계정과는 별개)
CREATE UNIQUE INDEX uq_users_local_email ON "users" (lower("email"))
  WHERE "provider" = 'LOCAL' AND "deleted_at" IS NULL;

-- 자체 로그인은 이메일 · 비밀번호, 카카오는 회원번호 필수
ALTER TABLE "users" ADD CONSTRAINT ck_users_provider_credentials CHECK (
  ("provider" = 'LOCAL' AND "email" IS NOT NULL AND "password" IS NOT NULL)
  OR ("provider" = 'KAKAO' AND "provider_id" IS NOT NULL));

-- ───────── refresh 토큰 ─────────
CREATE TABLE "refresh_token" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" bigint NOT NULL,
  "token_hash" varchar(64) UNIQUE NOT NULL,
  "expires_at" timestamp NOT NULL,
  "revoked_at" timestamp,
  "created_at" timestamp NOT NULL,
  "updated_at" timestamp NOT NULL,
  "deleted_at" timestamp
);

COMMENT ON TABLE "refresh_token" IS '재발급마다 회전. 폐기된 토큰이 다시 오면 해당 사용자 토큰 전부 폐기 (탈취 감지)';
COMMENT ON COLUMN "refresh_token"."token_hash" IS 'refresh 토큰 SHA-256 (원문은 저장하지 않음)';
COMMENT ON COLUMN "refresh_token"."revoked_at" IS '폐기 시각 (회전 · 로그아웃 · 탈취 감지)';

ALTER TABLE "refresh_token" ADD FOREIGN KEY ("user_id") REFERENCES "users" ("id");

CREATE INDEX idx_refresh_token_user ON "refresh_token" ("user_id");
