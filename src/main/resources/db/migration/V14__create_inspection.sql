CREATE TABLE inspection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    drain_id BIGINT NOT NULL REFERENCES drain(id),
    adoption_id BIGINT REFERENCES adoption(id),
    request_id BIGINT UNIQUE REFERENCES inspection_request(id),
    kind varchar NOT NULL,
    status varchar NOT NULL,
    before_photo_key varchar NOT NULL,
    after_photo_key varchar,
    before_grade integer,
    after_grade integer,
    ai_confidence numeric(3,2),
    after_confidence numeric(3,2),
    distance_m integer NOT NULL,
    captured_at timestamp NOT NULL,
    note varchar,
    xp_awarded integer NOT NULL DEFAULT 0,
    rewarded boolean NOT NULL DEFAULT false,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL,
    deleted_at timestamp
);
CREATE INDEX ix_inspection_user_created ON inspection(user_id, created_at DESC);
CREATE INDEX ix_inspection_adoption_created ON inspection(adoption_id, created_at DESC);
